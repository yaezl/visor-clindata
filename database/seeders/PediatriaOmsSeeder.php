    private function insertPercentiles(int $paramId, string $sexo, array $filas): void
    {
        $rows = array_map(fn ($f) => [
            'pediatria_parametro_id' => $paramId,
            'sexo' => $sexo,
            'mes'  => $f[0],
            'p3'   => $f[1],
            'p15'  => $f[2],
            'p50'  => $f[3],
            'p85'  => $f[4],
            'p97'  => $f[5],
        ], $filas);

        // Insertar en lotes para no saturar la query
        foreach (array_chunk($rows, 50) as $chunk) {
            DB::table('pediatria_percentil')->insertOrIgnore($chunk);
        }
    }
